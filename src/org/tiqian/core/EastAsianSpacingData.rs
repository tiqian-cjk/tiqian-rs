use super::EastAsianSpacing::EastAsianSpacingValue;

pub(crate) fn lookup(code_point: i32) -> EastAsianSpacingValue {
    let mut low = 0_usize;
    let mut high = RANGES.len() / 3;
    while low < high {
        let middle = (low + high) >> 1;
        let base = middle * 3;
        if code_point < RANGES[base] {
            high = middle;
        } else if code_point > RANGES[base + 1] {
            low = middle + 1;
        } else {
            return match RANGES[base + 2] {
                0 => EastAsianSpacingValue::Wide,
                1 => EastAsianSpacingValue::Narrow,
                3 => EastAsianSpacingValue::Conditional,
                _ => panic!("Invalid generated East_Asian_Spacing value"),
            };
        }
    }
    EastAsianSpacingValue::Other
}

